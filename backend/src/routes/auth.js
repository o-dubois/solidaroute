/**
 * @file auth.js
 * @module routes/auth
 * @description Authentication routes for SolidaRoute — /api/auth/*
 *
 * Handles account creation, email verification, login, and identity retrieval
 * for all user roles (client, driver, operator, admin, superadmin).
 *
 * ---------------------------------------------------------------------------
 * PUBLIC ROUTES (no JWT required):
 *   POST /register             — Create a new client or driver account
 *   POST /login                — Authenticate and receive a JWT
 *   GET  /verify-email         — Activate account via emailed link
 *   POST /resend-verification  — Re-send the activation email
 *   GET  /password-rules       — Return current complexity rules (for frontend display)
 *
 * PROTECTED ROUTES (JWT Bearer token required):
 *   GET  /me                   — Return the authenticated user's full profile
 *
 * ---------------------------------------------------------------------------
 * EMAIL VERIFICATION FLOW:
 *   1. User registers → account inserted with status='pending', email_verified=false
 *   2. A 96-character hex token is stored in the `verification_tokens` table (24h TTL)
 *   3. A verification email is dispatched; if SMTP is unconfigured, the link is
 *      logged to the console instead (dev-friendly fallback)
 *   4. User clicks link → GET /verify-email?token=<hex>
 *   5. Client accounts transition to status='active' immediately
 *      Driver accounts remain status='pending' — a human operator must approve them
 *      before they can log in (extra trust gate for volunteers handling passengers)
 *
 * ---------------------------------------------------------------------------
 * PASSWORD HASHING COMPATIBILITY NOTE:
 *   Hashes generated by PostgreSQL's pgcrypto extension carry a `$2a$` prefix.
 *   The bcryptjs library in Node.js expects `$2b$`. The normalizeHash() helper
 *   converts `$2a$` → `$2b$` on the fly so login works correctly whether the
 *   hash was created by the DB seed/migration or by the Node.js registration flow.
 *
 * ---------------------------------------------------------------------------
 * @requires express
 * @requires bcryptjs
 * @requires jsonwebtoken
 * @requires crypto
 * @requires express-validator
 * @requires ../db/pool
 * @requires ../middleware/auth
 * @requires ../services/email
 * @requires ../services/password
 * @requires ../utils/logger
 * @requires ../utils/phone
 */

// routes/auth.js
const express    = require('express');
const bcrypt     = require('bcryptjs');
const jwt        = require('jsonwebtoken');
const crypto     = require('crypto');
const fs         = require('fs');
const path       = require('path');
const rateLimit  = require('express-rate-limit');
const { body, validationResult } = require('express-validator');
const { pool }                = require('../db/pool');
const { authenticate }        = require('../middleware/auth');
const { sendVerificationEmail, sendPasswordResetEmail } = require('../services/email');
const { validatePassword, getPasswordRules } = require('../services/password');
const { logger }              = require('../utils/logger');
const { normalizePhone }      = require('../utils/phone');

// 10 attempts per 15 minutes per IP — blocks brute-force without locking out
// legitimate users who mistype their password a few times.
const loginLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 10,
  skipSuccessfulRequests: true,
  message: { error: 'Too many login attempts. Please try again in 15 minutes.' },
});

// 5 requests per hour per IP — prevents email flooding via the reset endpoint.
const forgotPasswordLimiter = rateLimit({
  windowMs: 60 * 60 * 1000,
  max: 5,
  message: { error: 'Too many password reset requests. Please try again in an hour.' },
});

// 10 registrations per hour per IP — limits bcrypt CPU load, account flooding,
// and email enumeration via the 409 EMAIL_IN_USE response code.
const registerLimiter = rateLimit({
  windowMs: 60 * 60 * 1000,
  max: 10,
  message: { error: 'Too many registration attempts. Please try again in an hour.' },
});

// 5 resend requests per hour per IP — prevents email bombing a victim's inbox.
const resendVerificationLimiter = rateLimit({
  windowMs: 60 * 60 * 1000,
  max: 5,
  message: { error: 'Too many verification email requests. Please try again in an hour.' },
});

const router = express.Router();

// Path to the registration lock file.
// Create this file on the server to disable self-registration for clients
// and drivers: touch backend/REGISTRATION_DISABLED
// Remove it to re-enable: rm backend/REGISTRATION_DISABLED
// Takes effect on the next request — no server restart required.
const REGISTRATION_LOCK_FILE = path.join(__dirname, '../../REGISTRATION_DISABLED');

/** Fetch the configured application name from the database. Falls back to 'SolidaRoute'. */
async function getAppName() {
  try {
    const { rows } = await pool.query("SELECT value FROM configuration WHERE key = 'app_name'");
    return rows[0]?.value || 'SolidaRoute';
  } catch { return 'SolidaRoute'; }
}

/**
 * Normalizes a bcrypt hash from PostgreSQL's `$2a$` variant to the `$2b$`
 * variant that bcryptjs expects.
 *
 * Background: both `$2a$` and `$2b$` are algorithmically identical; the prefix
 * difference is purely a library convention. pgcrypto emits `$2a$`, while
 * Node's bcryptjs produces `$2b$`. Without this fix, `bcrypt.compare()` would
 * fail for any password set via a DB migration or seed script.
 *
 * @param {string|null|undefined} hash - The raw hash stored in the database.
 * @returns {string|null|undefined} Hash with prefix converted if necessary.
 */
function normalizeHash(hash) {
  // Only swap the prefix when it is the pgcrypto variant; leave $2b$ hashes
  // (produced by this service) and any unexpected prefix values untouched.
  return hash?.startsWith('$2a$') ? '$2b$' + hash.slice(4) : hash;
}

/**
 * Generates a cryptographically secure random token for email verification
 * and password-reset flows.
 *
 * 48 random bytes → 96 hex characters. This gives 384 bits of entropy,
 * making brute-force guessing computationally infeasible.
 *
 * @returns {string} 96-character lowercase hex string.
 */
function generateToken() {
  // crypto.randomBytes uses the OS CSPRNG — safe for security-sensitive tokens.
  return crypto.randomBytes(48).toString('hex');
}


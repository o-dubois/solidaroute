/**
 * Returns the current password complexity rules stored in the `configuration`
 * table (e.g. min_length, require_uppercase, require_number, require_symbol).
 *
 * This endpoint is public so the registration form can display live feedback
 * to the user before they submit, without needing to be logged in.
 *
 * Auth:    None
 * Method:  GET
 * Returns: { rules: { ... } }
 */
router.get('/password-rules', async (_req, res, next) => {
  try {
    // Delegate to the password service, which reads from the `configuration` table.
    // Surfacing this data to the frontend prevents "password rejected" surprises
    // after the user fills in the entire registration form.
    const rules = await getPasswordRules();
    res.json({ rules });
  } catch (err) { next(err); }
});

// ─────────────────────────────────────────────────────────────────────────────
// POST /api/auth/register
// ─────────────────────────────────────────────────────────────────────────────
/**
 * Creates a new user account for the `client` or `driver` role.
 *
 * Auth:    None (public)
 * Method:  POST
 * Body:    { email, password, first_name, last_name, phone?, role }
 *
 * Business rules:
 *   - Only `client` and `driver` roles can self-register; operator/admin/superadmin
 *     accounts are created by existing admins through the admin panel.
 *   - Password must pass the dynamic complexity rules from the `configuration` table.
 *   - Email must be unique across all non-deleted accounts.
 *   - All new accounts start as status='pending' with email_verified=false.
 *   - Email delivery failures are logged but do NOT cause a 500 — the user is
 *     told to check their inbox; they can use /resend-verification if needed.
 *   - The registration action is written to `audit_logs` for traceability.
 *
 * Returns on success (201):
 *   { message, email_sent_to }
 */
router.post('/register',
  registerLimiter,
  [
    // Validate and sanitize all required fields before touching the DB.
    // normalizeEmail() lowercases and strips aliasing so duplicates are caught
    // consistently (e.g. "User+Tag@Example.COM" → "user@example.com").
    body('email').isEmail().normalizeEmail(),
    body('password').notEmpty().withMessage('Password is required'),
    body('first_name').trim().notEmpty().withMessage('First name is required'),
    body('last_name').trim().notEmpty().withMessage('Last name is required'),
    // Only clients and drivers may self-register; operator/admin/superadmin
    // accounts require creation through the privileged admin panel to prevent
    // unauthorised privilege escalation at registration time.
    body('role').isIn(['client', 'driver']).withMessage('Invalid role'),
  ],
  async (req, res, next) => {
    try {
      // Registration lock — checked on every request so toggling the file takes
      // effect immediately without restarting the server.
      if (fs.existsSync(REGISTRATION_LOCK_FILE)) {
        return res.status(503).json({
          error: 'Registration is currently disabled. Please contact the administrator.',
          code:  'REGISTRATION_DISABLED',
        });
      }

      // Return all validation errors at once so the frontend can highlight
      // every broken field in a single round-trip, improving UX.
      const errors = validationResult(req);
      if (!errors.isEmpty()) return res.status(422).json({ errors: errors.array() });

      const { email, password, first_name, last_name, phone, role } = req.body;

      // Check password complexity against rules stored in the `configuration` table.
      // Done BEFORE the duplicate-email check: a bad password is the most common
      // input error, so we fail fast without making a needless DB round-trip.
      const validation = await validatePassword(password);
      if (!validation.valid) {
        return res.status(422).json({
          error: 'Password does not meet security requirements.',
          // Return all failing rules so the frontend can display a checklist
          password_errors: validation.errors,
        });
      }

      // Prevent duplicate accounts — we check on the normalized email (lowercased by
      // normalizeEmail() above) so "User@example.com" and "user@example.com" are
      // treated as the same address.
      const existing = await pool.query(
        'SELECT id FROM users WHERE email = $1', [email]
      );
      if (existing.rows.length) {
        // 409 Conflict — the resource (email address) already belongs to another account.
        return res.status(409).json({ error: 'This email address is already in use.' });
      }

      // Hash the password using bcrypt with cost factor 10.
      // Cost 10 is a reasonable balance between security and registration latency
      // (~100 ms on modern hardware), and is the bcryptjs default recommendation.
      // Increasing this value would make offline dictionary attacks slower but also
      // slow down every registration.
      const password_hash = await bcrypt.hash(password, 10);

      // Insert the new user. All accounts start as:
      //   status='pending'       — cannot log in until email is verified (clients),
      //                            or until an operator also approves (drivers).
      //   email_verified=FALSE   — blocks login even if status is later changed externally
      //                            (e.g. by a script or a manual DB edit).
      const { rows } = await pool.query(
        `INSERT INTO users
           (email, password_hash, first_name, last_name, phone, role, status, email_verified)
         VALUES ($1, $2, $3, $4, $5, $6, 'pending', FALSE)
         RETURNING id, email, first_name, last_name, role, status`,
        [email, password_hash, first_name, last_name, normalizePhone(phone), role]
      );

      const user = rows[0];

      // Generate a secure token and persist it with a 24-hour expiry.
      // The token is single-use — it will be marked used_at on redemption so it
      // cannot be replayed by someone who intercepts the email.
      const token = generateToken();
      await pool.query(
        `INSERT INTO verification_tokens (user_id, token, type, expires_at)
         VALUES ($1, $2, 'email_verification', NOW() + INTERVAL '24 hours')`,
        [user.id, token]
      );

      // Attempt to send the verification email. This is wrapped in its own
      // try/catch so an SMTP outage does not roll back the successful registration.
      // The user will see a success page and can use POST /resend-verification
      // to request a fresh link if the first one never arrived.
      try {
        const appName = await getAppName();
        await sendVerificationEmail({ firstName: first_name, email, token, appName });
      } catch (emailErr) {
        // Log the SMTP error but swallow it — registration is still complete.
        logger.error('Failed to send verification email', { message: emailErr.message });
      }

      // Write an audit log entry recording the new account registration.
      // Failures here are non-fatal — we warn rather than error so that a
      // transient logging hiccup does not prevent successful registration.
      try {
        await pool.query(
          `INSERT INTO audit_logs (actor_id, action, entity_type, entity_id, new_state)
           VALUES ($1, 'user.registered', 'user', $2, jsonb_build_object('role', $3))`,
          [user.id, user.id, role]
        );
      } catch (e) { logger.warn('Audit log failed', { message: e.message }); }

      // 201 Created — do not return a JWT here; the user must verify their email first.
      res.status(201).json({
        message: `Account created! A confirmation email has been sent to ${email}. Please click the link to activate your account.`,
        email_sent_to: email,
      });
    } catch (err) { next(err); }
  }
);

// ─────────────────────────────────────────────────────────────────────────────
// GET /api/auth/verify-email?token=<hex>
// ─────────────────────────────────────────────────────────────────────────────
/**
 * Activates a user account by redeeming a one-time email verification token.
 * The token is embedded in the link sent by POST /register and
 * POST /resend-verification.
 *
 * Auth:    None (public — the token itself acts as proof of email ownership)
 * Method:  GET
 * Query:   token — 96-char hex token from the verification email
 *
 * Business rules:
 *   - Tokens expire after 24 hours (set at creation time).
 *   - Tokens are single-use; redeeming a token sets `used_at`.
 *   - Client accounts: status set to 'active' → they can now log in.
 *   - Driver accounts: status stays 'pending' → an operator must still approve
 *     the driver before they can log in (see operator/admin approval flow).
 *   - Distinct error codes (TOKEN_INVALID, TOKEN_ALREADY_USED, TOKEN_EXPIRED)
 *     are returned so the frontend can show context-appropriate messages.
 *
 * Returns on success (200):
 *   { message, role, first_name }
 */
router.get('/verify-email', async (req, res, next) => {
  try {
    const { token } = req.query;
    if (!token) return res.status(400).json({ error: 'Token missing.' });

    // JOIN with users to fetch the role — we need it to decide the
    // post-verification status and to personalise the success message.
    // Filter by type='email_verification' so this endpoint cannot accidentally
    // redeem a password-reset token.
    const { rows } = await pool.query(
      `SELECT vt.id, vt.user_id, vt.used_at, vt.expires_at,
              u.role, u.first_name, u.email_verified
       FROM verification_tokens vt
       JOIN users u ON u.id = vt.user_id
       WHERE vt.token = $1 AND vt.type = 'email_verification'`,
      [token]
    );

    if (!rows.length) {
      // Could be a fabricated token, a deleted token, or a copy-paste error.
      // Treat all of these identically to avoid leaking information about the DB.
      return res.status(404).json({ error: 'Invalid or non-existent verification link.', code: 'TOKEN_INVALID' });
    }

    const entry = rows[0];

    // Guard: token already redeemed (used_at is set).
    // 410 Gone is more precise than 400 here — the resource existed and was consumed.
    if (entry.used_at) {
      return res.status(410).json({ error: 'This link has already been used. Your email is already confirmed.', code: 'TOKEN_ALREADY_USED' });
    }

    // Guard: token window has passed (24h from creation).
    // The user will need to request a fresh link via POST /resend-verification.
    if (new Date() > new Date(entry.expires_at)) {
      return res.status(410).json({ error: 'This verification link has expired (valid 24h). Please request a new one.', code: 'TOKEN_EXPIRED' });
    }

    // Consume the token AND activate the account in a single transaction so that
    // if the user UPDATE fails the token is not left in a consumed state and the
    // user can retry by clicking the link again.
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      await client.query(
        'UPDATE verification_tokens SET used_at = NOW() WHERE id = $1',
        [entry.id]
      );
      // All roles transition to status='active' after email verification so they
      // can log in immediately.  The admin review queue for drivers is triggered
      // automatically (approval_status: 'incomplete' → 'pending') once the driver
      // fills all required fields and uploads any required documents.
      await client.query(
        `UPDATE users SET email_verified = TRUE, status = 'active', updated_at = NOW()
         WHERE id = $1`,
        [entry.user_id]
      );
      await client.query('COMMIT');
    } catch (txErr) {
      await client.query('ROLLBACK');
      throw txErr;
    } finally {
      client.release();
    }

    // For drivers: create the driver_profiles row with approval_status='incomplete'
    // and seed service_radius_km from the admin-configured global setting.
    // This is intentionally NON-FATAL — if the INSERT fails (e.g. the migration
    // that adds 'incomplete' to the CHECK constraint hasn't been applied yet, or
    // the row already exists), the verification is still considered successful.
    // The profile row will be created on the driver's first profile save instead.
    if (entry.role === 'driver') {
      try {
        const { rows: cfg } = await pool.query(
          `SELECT value FROM configuration WHERE key = 'driver_suggestion_radius_km' LIMIT 1`
        );
        const radius = parseFloat(cfg[0]?.value || '10');
        await pool.query(
          `INSERT INTO driver_profiles
             (user_id, approval_status, service_radius_km,
              vehicle_make, vehicle_model, vehicle_year, license_plate, home_point)
           VALUES ($1, 'incomplete', $2, '', '', 2020, '',
                   ST_SetSRID(ST_MakePoint(0,0), 4326)::geography)
           ON CONFLICT (user_id) DO NOTHING`,
          [entry.user_id, radius]
        );
      } catch (profileErr) {
        // Log but do not abort — the driver can still log in and the profile row
        // will be created automatically on their first profile save.
        logger.warn('Could not pre-create driver_profiles row at verification time', {
          user_id: entry.user_id,
          message: profileErr.message,
        });
      }
    }

    // Audit log — non-fatal if it fails (same pattern as /register)
    try {
      await pool.query(
        `INSERT INTO audit_logs (actor_id, action, entity_type, entity_id, new_state)
         VALUES ($1, 'user.email_verified', 'user', $2,
                 '{"status":"active"}'::jsonb)`,
        [entry.user_id, entry.user_id]
      );
    } catch (e) { logger.warn('Audit log failed', { message: e.message }); }

    const message = entry.role === 'driver'
      ? 'Your email address is confirmed. You can now log in and complete your driver profile.'
      : 'Your email address is confirmed. You can now log in!';

    res.json({ message, role: entry.role, first_name: entry.first_name });
  } catch (err) { next(err); }
});

// ─────────────────────────────────────────────────────────────────────────────
// POST /api/auth/resend-verification
// ─────────────────────────────────────────────────────────────────────────────
/**
 * Re-sends the email verification link to a user whose token has expired or
 * was lost. Invalidates any previously active tokens for that user before
 * issuing a fresh one.
 *
 * Auth:    None (public)
 * Method:  POST
 * Body:    { email }
 *
 * Security note — enumeration protection:
 *   The same generic message is returned regardless of whether the address
 *   exists, is already verified, or is genuinely unverified. This prevents
 *   an attacker from using this endpoint to enumerate registered email addresses.
 *
 * Business rules:
 *   - If the email is unknown or already verified, silently return the generic
 *     message without sending anything.
 *   - All existing unused tokens are marked `used_at = NOW()` (invalidated)
 *     before the new token is inserted — ensures only the latest link works.
 *
 * Returns (200): { message }
 */
router.post('/resend-verification',
  resendVerificationLimiter,
  [ body('email').isEmail().normalizeEmail() ],
  async (req, res, next) => {
    try {
      const errors = validationResult(req);
      if (!errors.isEmpty()) return res.status(422).json({ errors: errors.array() });

      const { email } = req.body;

      // Generic message returned for ALL outcomes to prevent email enumeration.
      // Whether the account exists, is already verified, or needs a new token,
      // the caller always receives the same response text.
      const genericMsg = "If this address is associated with an unverified account, a new confirmation email has been sent.";

      const { rows } = await pool.query(
        // Exclude soft-deleted accounts — they should not receive verification emails
        `SELECT id, first_name, email_verified FROM users
         WHERE email = $1 AND status != 'deleted'`,
        [email]
      );

      // Silently return the generic message when:
      //   a) no account with that email exists (prevents enumeration), OR
      //   b) the account's email is already verified (nothing useful to do)
      if (!rows.length || rows[0].email_verified) {
        return res.json({ message: genericMsg });
      }

      const { id, first_name } = rows[0];

      // Invalidate all outstanding (unused) verification tokens for this user.
      // This closes the window for multiple valid links floating in the user's
      // inbox simultaneously, reducing the risk of token interception and replay.
      await pool.query(
        `UPDATE verification_tokens SET used_at = NOW()
         WHERE user_id = $1 AND type = 'email_verification' AND used_at IS NULL`,
        [id]
      );

      // Issue a fresh 24-hour token for the new email
      const token = generateToken();
      await pool.query(
        `INSERT INTO verification_tokens (user_id, token, type, expires_at)
         VALUES ($1, $2, 'email_verification', NOW() + INTERVAL '24 hours')`,
        [id, token]
      );

      // Non-fatal email send — same pattern as /register.
      // If SMTP is down the user will need to try again later;
      // logging the error gives ops visibility into delivery failures.
      try {
        const appName = await getAppName();
        await sendVerificationEmail({ firstName: first_name, email, token, appName });
      } catch (e) {
        logger.error('Failed to resend verification email', { message: e.message });
      }

      // Always return the same generic message regardless of actual outcome
      res.json({ message: genericMsg });
    } catch (err) { next(err); }
  }
);

// ─────────────────────────────────────────────────────────────────────────────
// POST /api/auth/login
// ─────────────────────────────────────────────────────────────────────────────
/**
 * Authenticates a user and issues a signed JWT stored as `sr_token`.
 *
 * Auth:    None (public)
 * Method:  POST
 * Body:    { email, password }
 *
 * Gate checks (in order — all must pass before a token is issued):
 *   1. Input validation (email format, non-empty password)
 *   2. Account must exist
 *   3. email_verified must be TRUE
 *   4. status must be 'active' (not pending/suspended/deleted)
 *   5. Password must match the stored bcrypt hash
 *
 * Security note — timing attack mitigation:
 *   The "user not found" and "wrong password" cases both return the same
 *   generic "Incorrect credentials" message and the same HTTP 401 status,
 *   preventing attackers from distinguishing registered vs unregistered emails.
 *
 * On success:
 *   - `last_login_at` is updated in the database.
 *   - `password_hash` and `email_verified` fields are stripped from the
 *     response payload before it is sent to the client.
 *
 * Returns (200): { token: <JWT>, user: { id, email, first_name, last_name, role, status } }
 */
router.post('/login',
  loginLimiter,
  [
    // normalizeEmail() ensures the lookup is case-insensitive and consistent
    body('email').isEmail().normalizeEmail(),
    body('password').notEmpty(),
  ],
  async (req, res, next) => {
    try {
      const errors = validationResult(req);
      if (!errors.isEmpty()) return res.status(422).json({ errors: errors.array() });

      const { email, password } = req.body;

      // Fetch all fields needed for gate checks in a single query.
      // password_hash is fetched here but MUST NOT appear in the response (stripped below).
      const { rows } = await pool.query(
        `SELECT id, email, password_hash, first_name, last_name, role, status,
                email_verified, failed_login_attempts, account_locked_at
         FROM users WHERE email = $1`,
        [email]
      );

      const user = rows[0];

      // Return 401 (not 404) to avoid confirming whether the email exists in the system.
      // This is intentionally the same response as a wrong password.
      if (!user) return res.status(401).json({ error: 'Incorrect credentials.' });

      // Email verification gate — must be cleared before any other status check.
      // We check this before status so the user gets an actionable error code
      // (EMAIL_NOT_VERIFIED) that lets the frontend offer a "resend" button,
      // rather than a generic "pending" message that doesn't explain what to do.
      if (!user.email_verified) {
        return res.status(403).json({
          error: 'You must confirm your email address before logging in. Check your inbox.',
          code: 'EMAIL_NOT_VERIFIED',
        });
      }

      // Auto-lockout gate — checked before the generic status block so the user
      // gets an actionable ACCOUNT_LOCKED code rather than a generic "suspended" message.
      // account_locked_at is set automatically after too many failed login attempts.
      if (user.account_locked_at) {
        return res.status(403).json({
          error: 'Your account has been locked after too many failed login attempts. Please contact an administrator to unlock it.',
          code: 'ACCOUNT_LOCKED',
        });
      }

      // Status checks — each yields a distinct user-visible message explaining
      // the specific reason the account cannot log in at this time.
      if (user.status === 'pending')   return res.status(403).json({ error: 'Your account is pending approval by an administrator.' });
      if (user.status === 'suspended') return res.status(403).json({ error: 'Your account has been suspended. Contact us for more information.' });
      if (user.status === 'deleted')   return res.status(403).json({ error: 'This account no longer exists.' });
      // Catch-all for any unexpected status values that are not explicitly handled above
      if (user.status !== 'active')    return res.status(403).json({ error: 'Inactive account.' });

      // Normalize the hash prefix before comparison — handles hashes originally
      // created by pgcrypto ($2a$) as well as those created by this Node.js service ($2b$).
      // See normalizeHash() above for full explanation.
      const normalizedHash = normalizeHash(user.password_hash);
      const valid = await bcrypt.compare(password, normalizedHash);

      if (!valid) {
        // Fetch the configured threshold (default 5 if not set).
        const { rows: cfg } = await pool.query(
          `SELECT value FROM configuration WHERE key = 'max_login_attempts' LIMIT 1`
        );
        const maxAttempts = parseInt(cfg[0]?.value || '5', 10);

        const { rows: updated } = await pool.query(
          `UPDATE users
           SET failed_login_attempts = failed_login_attempts + 1, updated_at = NOW()
           WHERE id = $1
           RETURNING failed_login_attempts`,
          [user.id]
        );
        const attempts = updated[0].failed_login_attempts;

        // Lock the account once the threshold is reached.
        // Sets account_locked_at and suspends the account so all subsequent
        // login attempts are rejected before even reaching the password check.
        if (attempts >= maxAttempts) {
          await pool.query(
            `UPDATE users
             SET status = 'suspended', account_locked_at = NOW(), updated_at = NOW()
             WHERE id = $1`,
            [user.id]
          );
        }

        // Same 401 as "user not found" — caller cannot distinguish wrong email from wrong password.
        return res.status(401).json({ error: 'Incorrect credentials.' });
      }

      // Successful login — reset the failed attempt counter and any lockout timestamp.
      // Record the login timestamp for the admin "last seen" display.
      await pool.query(
        `UPDATE users
         SET last_login_at = NOW(), failed_login_attempts = 0, account_locked_at = NULL
         WHERE id = $1`,
        [user.id]
      );

      // Sign the JWT. The payload contains only id and role — just enough for the
      // `authenticate` middleware to authorise requests without an additional DB lookup
      // on every call. Sensitive data (email, hash) is intentionally omitted from
      // the token payload.
      // Expiry defaults to 7 days; configurable via JWT_EXPIRES_IN env var.
      const jwtToken = jwt.sign(
        { id: user.id, role: user.role },
        process.env.JWT_SECRET,
        { expiresIn: process.env.JWT_EXPIRES_IN || '7d' }
      );

      // Destructure sensitive fields out of the user object before sending.
      // `password_hash` must NEVER leave the server.
      // `email_verified` is internal state the client does not need once logged in.
      const { password_hash: _, email_verified: __, ...userInfo } = user;
      res.json({ token: jwtToken, user: userInfo });
    } catch (err) { next(err); }
  }
);

// ─────────────────────────────────────────────────────────────────────────────
// POST /api/auth/forgot-password
// ─────────────────────────────────────────────────────────────────────────────
/**
 * Issues a password-reset email for any active account.
 *
 * Auth:    None (public)
 * Method:  POST
 * Body:    { email }
 *
 * Security: always returns the same generic message regardless of whether the
 * email exists, to prevent enumeration. Token expires in 1 hour. Any existing
 * unused password-reset tokens for the account are invalidated before issuing
 * the new one.
 *
 * Returns (200): { message }
 */
router.post('/forgot-password',
  forgotPasswordLimiter,
  [ body('email').isEmail().normalizeEmail() ],
  async (req, res, next) => {
    try {
      const errors = validationResult(req);
      if (!errors.isEmpty()) return res.status(422).json({ errors: errors.array() });

      const { email } = req.body;
      const genericMsg = 'If this email is associated with an account, a password reset link has been sent.';

      const { rows } = await pool.query(
        `SELECT u.id, u.first_name,
                COALESCE(
                  (SELECT value FROM configuration WHERE key = 'frontend_language'),
                  'fr'
                ) AS lang
         FROM users u
         WHERE u.email = $1 AND u.status != 'deleted'`,
        [email]
      );

      if (!rows.length) return res.json({ message: genericMsg });

      const { id, first_name, lang } = rows[0];

      // Invalidate any outstanding reset tokens before issuing a fresh one.
      await pool.query(
        `UPDATE verification_tokens SET used_at = NOW()
         WHERE user_id = $1 AND type = 'password_reset' AND used_at IS NULL`,
        [id]
      );

      const token = generateToken();
      await pool.query(
        `INSERT INTO verification_tokens (user_id, token, type, expires_at)
         VALUES ($1, $2, 'password_reset', NOW() + INTERVAL '1 hour')`,
        [id, token]
      );

      try {
        const appName = await getAppName();
        await sendPasswordResetEmail({ firstName: first_name, email, token, lang, appName });
      } catch (e) {
        logger.error('Failed to send password reset email', { message: e.message });
      }

      res.json({ message: genericMsg });
    } catch (err) { next(err); }
  }
);

// ─────────────────────────────────────────────────────────────────────────────
// POST /api/auth/reset-password
// ─────────────────────────────────────────────────────────────────────────────
/**
 * Resets the user's password using a one-time token from the reset email.
 *
 * Auth:    None (public — token is the proof of identity)
 * Method:  POST
 * Body:    { token, password }
 *
 * Business rules:
 *   - Token must exist, be unused, and not have expired (1h TTL).
 *   - New password must pass the configured complexity rules.
 *   - Token is consumed (used_at set) before the password is written, so a
 *     failure during the UPDATE cannot leave the token reusable.
 *   - Action is recorded in audit_logs for traceability.
 *
 * Returns (200): { message }
 */
router.post('/reset-password',
  [
    body('token').notEmpty(),
    body('password').notEmpty(),
  ],
  async (req, res, next) => {
    try {
      const errors = validationResult(req);
      if (!errors.isEmpty()) return res.status(422).json({ errors: errors.array() });

      const { token, password } = req.body;

      const { rows } = await pool.query(
        `SELECT vt.id, vt.user_id, vt.used_at, vt.expires_at
         FROM verification_tokens vt
         WHERE vt.token = $1 AND vt.type = 'password_reset'`,
        [token]
      );

      if (!rows.length) {
        return res.status(404).json({ error: 'Invalid or expired password reset link.', code: 'TOKEN_INVALID' });
      }

      const entry = rows[0];

      if (entry.used_at) {
        return res.status(410).json({ error: 'This reset link has already been used.', code: 'TOKEN_ALREADY_USED' });
      }

      if (new Date() > new Date(entry.expires_at)) {
        return res.status(410).json({ error: 'This reset link has expired. Please request a new one.', code: 'TOKEN_EXPIRED' });
      }

      // Validate password complexity against rules from the configuration table.
      const validation = await validatePassword(password);
      if (!validation.valid) {
        return res.status(422).json({
          error: 'Password does not meet security requirements.',
          password_errors: validation.errors,
        });
      }

      // Consume the token before updating the password so it cannot be reused
      // even if the subsequent UPDATE fails and is retried.
      await pool.query('UPDATE verification_tokens SET used_at = NOW() WHERE id = $1', [entry.id]);

      const hash = await bcrypt.hash(password, 10);
      await pool.query(
        `UPDATE users SET password_hash = $1, updated_at = NOW() WHERE id = $2`,
        [hash, entry.user_id]
      );

      try {
        await pool.query(
          `INSERT INTO audit_logs (actor_id, action, entity_type, entity_id, new_state)
           VALUES ($1, 'user.password_reset', 'user', $2, '{"method":"email_token"}'::jsonb)`,
          [entry.user_id, entry.user_id]
        );
      } catch (e) { logger.warn('Audit log failed', { message: e.message }); }

      res.json({ message: 'Password successfully reset. You can now log in.' });
    } catch (err) { next(err); }
  }
);

// ─────────────────────────────────────────────────────────────────────────────
// GET /api/auth/me
// ─────────────────────────────────────────────────────────────────────────────
/**
 * Returns the full profile of the currently authenticated user, including
 * their role-specific sub-profile (client_profiles or driver_profiles).
 *
 * Auth:    Required (JWT via `authenticate` middleware)
 * Method:  GET
 *
 * The role-specific profile is fetched in a second query rather than a JOIN
 * so that the response shape is always predictable: the base user fields are
 * always present, and `profile` contains the sub-profile object or null if
 * it has not been filled out yet.
 *
 * Returns (200): { user: { ...fields, profile: { ... } | null } }
 */
router.get('/me', authenticate, async (req, res, next) => {
  try {
    // Exclude password_hash and email_verified — these are internal fields
    // that should never appear in a "who am I?" response.
    const { rows } = await pool.query(
      `SELECT id, email, first_name, last_name, phone, role, status,
              member_number, created_at, last_login_at
       FROM users WHERE id = $1`,
      [req.user.id]
    );
    if (!rows.length) return res.status(404).json({ error: 'User not found.' });

    const user = rows[0];

    // Conditionally attach the role-specific sub-profile so the frontend
    // receives everything it needs in a single request.
    // A null value signals "profile not yet filled out" — handled gracefully by the UI.
    if (user.role === 'client') {
      const { rows: profile } = await pool.query(
        `SELECT id, user_id, vulnerability_type, address, home_point,
                emergency_contact_name, emergency_contact_phone,
                preferred_language, notes, created_at, updated_at
         FROM client_profiles WHERE user_id = $1`, [user.id]
      );
      user.profile = profile[0] || null;
    } else if (user.role === 'driver') {
      const { rows: profile } = await pool.query(
        `SELECT id, user_id, vehicle_make, vehicle_model, vehicle_year,
                vehicle_color, license_plate, seat_count,
                home_address, service_radius_km, is_available,
                approval_status, avg_rating, total_trips,
                created_at, updated_at
         FROM driver_profiles WHERE user_id = $1`, [user.id]
      );
      user.profile = profile[0] || null;
    }
    // Operators, admins, and superadmins have no sub-profile table;
    // the `profile` key is simply absent from their response.

    res.json({ user });
  } catch (err) { next(err); }
});

